export const blankProcRows = () => I_PROCS.map((p) => ({ key: p.key, custom: false, checked: false, date: '', notes: '' }));
export const newCustomRow = () => ({ custom: true, name: '', checked: false, date: '', notes: '' });

// iAutoCheck القديمة: الكتابة تحدّد الصف ولا تُلغي التحديد أبداً
export function editProcRow(rows, idx, field, value) {
  return rows.map((r, i) => {
    if (i !== idx) return r;
    const next = { ...r, [field]: value };
    if (field !== 'checked' && String(value).trim()) next.checked = true;
    return next;
  });
}

// iProcDetails: المخصَّص يُحفظ إن كان له اسم (ولو بلا تحديد)، والثابت إن كان محدداً
export function procDetails(rows) {
  const out = [];
  (rows || []).forEach((r) => {
    const date = r.date || '';
    const notes = v(r.notes);
    if (r.custom) {
      const name = v(r.name);
      if (name) out.push({ custom: true, name, date, notes });
    } else if (r.checked) {
      const p = I_PROCS.find((x) => x.key === r.key);
      if (p) out.push({ key: p.key, name: p.name, date, notes });
    }
  });
  return out;
}
// iProcNames: الأسماء المختصرة المحفوظة في entry.procedures
export const procNames = (rows) => procDetails(rows).map((r) => (r.custom ? r.name : (I_PROCS.find((x) => x.key === r.key) || {}).arch));

// iLoadEntry + iRestoreProcRows: تُلغى كل الثابتة، ثم تُحدَّد بأسمائها المختصرة، ثم تُستعاد الصفوف المحفوظة (تاريخ/ملاحظات + تحديد) والمخصَّصة تُضاف بالترتيب
export function procRowsForLoad(entry) {
  const rows = blankProcRows();
  (entry.procedures || []).forEach((p) => { const def = I_PROCS.find((x) => x.arch === p); const row = def && rows.find((x) => x.key === def.key); if (row) row.checked = true; });
  (entry.procedureRows || []).forEach((r) => {
    if (r.custom) { rows.push({ custom: true, name: r.name || '', checked: true, date: r.date || '', notes: r.notes || '' }); return; }
    const row = rows.find((x) => x.key === r.key);
    if (!row) return;
    row.date = r.date || ''; row.notes = r.notes || ''; row.checked = true;
  });
  return rows;
}

